ser_num <- function(x) {
  if (is.nan(x)) return("NaN")
  if (is.na(x)) return("NA")
  if (is.infinite(x)) return(if (x > 0) "Inf" else "-Inf")
  sprintf("%.17g", x)
}
ser <- function(x) {
  if (is.null(x)) return("NULL")
  if (length(x) == 0) return("EMPTY")
  elems <- vapply(seq_along(x), function(i) {
    e <- x[i]
    if (is.numeric(e)) ser_num(as.numeric(e))
    else if (is.logical(e)) { if (is.na(e)) "NA" else if (e) "TRUE" else "FALSE" }
    else if (is.character(e)) { if (is.na(e)) "NA" else paste0('"', e, '"') }
    else "OTHER"
  }, character(1))
  paste0("[", paste(elems, collapse = ","), "]")
}
run_case <- function(id, expr) {
  warns <- 0
  val <- tryCatch(
    withCallingHandlers(expr, warning = function(w) { warns <<- warns + 1; invokeRestart("muffleWarning") }),
    error = function(e) structure(list(msg = conditionMessage(e)), class = "perr")
  )
  if (inherits(val, "perr")) {
    cat(id, "\t1\t", warns, "\t-\t", val$msg, "\n", sep = "")
  } else {
    cat(id, "\t0\t", warns, "\t", ser(val), "\t\n", sep = "")
  }
}
