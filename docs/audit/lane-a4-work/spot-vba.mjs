import { getDefinition } from "../../../js/types/registry.js";
import { loadAdvanced, clearAdvancedCache } from "../../../js/core/advanced-loader.js";
import { mergeCatalog } from "../../../js/core/catalog.js";
const vba = getDefinition("vba");
clearAdvancedCache();
const adv = await loadAdvanced(vba);
const merged = mergeCatalog({ reference: vba.reference, templates: vba.templates, glossary: vba.glossary }, adv);
const byName = (n) => merged.reference.find((r) => r.name === n);
console.log("Len caution:", byName("Len")?.caution ?? "(none)");
console.log("VarType caution:", (byName("VarType")?.caution ?? "(none)").slice(0, 120));
console.log("Hex caution:", (byName("Hex")?.caution ?? "(none)").slice(0, 120));
console.log("AscW item:", byName("AscW") ? "exists" : "absent", "| ChrW item:", byName("ChrW") ? "exists" : "absent", "| LenB item:", byName("LenB") ? "exists" : "absent");
const run = async (body) => vba.simulate(`Sub Main()\n${body}\nEnd Sub`, structuredClone(vba.model.defaults));
const r1 = await run('Debug.Print Len("𐮷")');
console.log('Len("𐮷"):', JSON.stringify(r1.paths?.[0]?.outputs?.map(o=>o.text)), "err:", JSON.stringify(r1.paths?.[0]?.error ?? r1.error ?? null));
const r2 = await run('x = String(1000000, "a")\nDebug.Print Len(x)');
const p2 = r2.paths?.[0];
console.log("VB13 truncated:", r2.truncated, "| outputs:", JSON.stringify(p2?.outputs?.map(o=>o.text)), "| trace kinds:", JSON.stringify((p2?.trace??[]).map(t=>t.kind)));
console.log("VB13 final vars:", JSON.stringify(p2?.finalState ?? p2?.variables ?? null)?.slice(0,200));
