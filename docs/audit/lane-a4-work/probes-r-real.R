## 各式をそのまま実行し、値・警告・エラーと typeof を正規形で出す。
fmt <- function(x) {
  if (is.null(x)) return("NULL")
  if (length(x) == 0) return(paste0(typeof(x), "(0)"))
  paste(format(x, scientific = FALSE, trim = TRUE), collapse = ",")
}
run1 <- function(id, expr) {
  warns <- character(0)
  val <- tryCatch(
    withCallingHandlers(expr, warning = function(w) {
      warns <<- c(warns, conditionMessage(w)); invokeRestart("muffleWarning")
    }),
    error = function(e) structure(list(err = conditionMessage(e)), class = "perr")
  )
  if (inherits(val, "perr")) {
    cat(id, "\terr=", val$err, "\n", sep = "")
  } else {
    cat(id, "\tval=", fmt(val), "\ttypeof=", typeof(val),
        "\twarn=", paste(warns, collapse = " | "), "\n", sep = "")
  }
}
