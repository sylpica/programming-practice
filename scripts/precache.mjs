import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { pathToFileURL } from "node:url";
const root = new URL("../", import.meta.url).pathname;
function walk(dir) {
  return fs
    .readdirSync(path.join(root, dir), { withFileTypes: true })
    .flatMap((e) =>
      e.isDirectory() ? walk(dir + "/" + e.name) : [dir + "/" + e.name],
    );
}

// ファイルの分類はファイル名ではなく到達方法の実態で行う（修正バッチ20・
// RG-681）。旧方式は「-advanced を含む .js」を一律に遅延読み込み扱いして
// precache から除外していたが、静的 import される高度エンジン・名前照合表
// まで落ちており、新世代の初回起動をオフラインで行うとランタイムキャッシュ
// が空のため簡易モードでも白紙になっていた（precache 集合だけの配信では
// 起動必須の38ファイルが 404 になることを実ブラウザで確認済み）。
//
// - 起動閉包 → precache：入口（index.html が読み込む js/app.js と、その
//   Worker である js/worker.js）から、静的 import とリテラルな動的 import
//   を辿って到達できるファイル。起動時に必須なコード一式。
// - 遅延集合 → sw.js のランタイムキャッシュ（network-first）：残りの js
//   ファイル。高度ローダー（js/core/advanced-loader.js）が manifest に
//   従って動的 import する項目データ本体（reference-advanced 群など）が
//   ここに入り、簡易モードの初期ロードでは取得されない（SP-21 の遅延
//   読み込み契約）。sw.js は生成された遅延集合への所属で判定し、分類の
//   正本はこの生成器に一本化する。
const STATIC_IMPORT_RE =
  /(?:import|export)\s+(?:[^"']*?\s+from\s+)?["']([^"']+)["']/g;
const LITERAL_DYNAMIC_IMPORT_RE = /import\s*\(\s*["']([^"']+)["']\s*\)/g;
function importTargets(file) {
  const src = fs.readFileSync(path.join(root, file), "utf8");
  const targets = [];
  for (const re of [STATIC_IMPORT_RE, LITERAL_DYNAMIC_IMPORT_RE])
    for (const m of src.matchAll(re)) {
      if (!m[1].startsWith(".")) continue;
      const resolved = path.posix.normalize(
        path.posix.join(path.posix.dirname(file), m[1]),
      );
      if (resolved.endsWith(".js")) targets.push(resolved);
    }
  return targets;
}
function bootClosure() {
  const seen = new Set();
  const queue = ["js/app.js", "js/worker.js"];
  while (queue.length) {
    const file = queue.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    if (!fs.existsSync(path.join(root, file)))
      throw new Error(`precache: import 先が存在しません: ${file}`);
    queue.push(...importTargets(file));
  }
  return seen;
}
// SP-21 の回帰防止：ローダーが項目データ本体として読みうるファイル
// （manifest の referenceParts／templatesFile／glossaryFile。manifest の
// 無い種別はローダーの既定ファイル）が起動閉包に入っていたら、それは
// 静的 import によるデータ本体の混入なので生成を失敗させる。engineFile
// は静的合成される種別がある（cmd／UI.Vision 等）ため対象外とする。
async function loaderDataFiles() {
  const DEFAULTS = {
    referenceParts: ["reference-advanced.js"],
    templatesFile: "templates-advanced.js",
    glossaryFile: "glossary-advanced.js",
  };
  const declared = new Set();
  for (const entry of fs.readdirSync(path.join(root, "js/types"), {
    withFileTypes: true,
  })) {
    if (!entry.isDirectory()) continue;
    const dir = "js/types/" + entry.name;
    let manifest = DEFAULTS;
    const manifestPath = path.join(root, dir, "advanced-manifest.js");
    if (fs.existsSync(manifestPath)) {
      const mod = await import(pathToFileURL(manifestPath).href);
      const m = mod?.advancedManifest;
      if (m && typeof m === "object" && !Array.isArray(m))
        manifest = {
          referenceParts: Array.isArray(m.referenceParts)
            ? m.referenceParts
            : DEFAULTS.referenceParts,
          templatesFile:
            m.templatesFile === undefined
              ? DEFAULTS.templatesFile
              : m.templatesFile,
          glossaryFile:
            m.glossaryFile === undefined
              ? DEFAULTS.glossaryFile
              : m.glossaryFile,
        };
    }
    const names = [
      ...manifest.referenceParts,
      manifest.templatesFile,
      manifest.glossaryFile,
    ].filter((f) => typeof f === "string" && f);
    for (const name of names) {
      const p = dir + "/" + name;
      if (fs.existsSync(path.join(root, p))) declared.add(p);
    }
  }
  return declared;
}
const boot = bootClosure();
for (const f of await loaderDataFiles())
  if (boot.has(f))
    throw new Error(
      `precache: 項目データ本体が起動閉包に混入しています（SP-21）: ${f}`,
    );
const lazyFiles = walk("js")
  .filter((f) => f.endsWith(".js") && !boot.has(f))
  .sort();
const files = [
  "index.html",
  "style.css",
  "sw.js",
  "manifest.webmanifest",
  // js 配下の非 .js ファイル（vendor のライセンス等）は従来どおり含める。
  ...walk("js").filter((f) => !f.endsWith(".js") || boot.has(f)),
  ...walk("icons"),
].sort();
const hash = crypto.createHash("sha256");
for (const file of files)
  hash.update(file).update(fs.readFileSync(path.join(root, file)));
// 遅延集合はファイル名のみを世代ハッシュに含める（集合の増減で世代が
// 変わり、旧世代のランタイムキャッシュが破棄される。内容の鮮度は
// network-first が担う）。
for (const file of lazyFiles) hash.update("lazy:").update(file);
const output =
  "// Generated by node scripts/precache.mjs; the app needs no build step.\nself.PROGRAMMING_CACHE=" +
  JSON.stringify("programming-practice-" + hash.digest("hex").slice(0, 14)) +
  ";\nself.PROGRAMMING_ASSETS=" +
  JSON.stringify([
    "./",
    "./precache.js",
    ...files.filter((f) => f !== "sw.js").map((f) => "./" + f),
  ]) +
  ";\nself.PROGRAMMING_LAZY_ASSETS=" +
  JSON.stringify(lazyFiles.map((f) => "./" + f)) +
  ";\n";
if (process.argv.includes("--check")) {
  if (fs.readFileSync(path.join(root, "precache.js"), "utf8") !== output) {
    console.error("Precache manifest is stale. Run node scripts/precache.mjs");
    process.exit(1);
  }
} else fs.writeFileSync(path.join(root, "precache.js"), output);
